# ZARRAR one-click launcher.
#
# Started by Zarrar.exe (or: powershell -ExecutionPolicy Bypass -File launcher\ZARRAR-Launcher.ps1).
#   1. starts Docker Desktop and waits for the engine
#   2. on the first run, writes deploy/production/.env.zarrar with fresh random secrets
#   3. builds (first run only, or with -Rebuild) and starts the stack: Caddy, app, Postgres, Redis, MinIO
#   4. trusts Caddy's local HTTPS certificate for the current Windows user (asked once)
#   5. creates the demo accounts once and writes them to DEMO_ACCOUNTS.txt
#   6. opens the platform in the browser
#
# -Stop stops the stack (data is kept in Docker volumes). -Rebuild rebuilds the app image after code changes.

param(
    [switch]$Stop,
    [switch]$Rebuild,
    [switch]$NoBrowser,
    [switch]$NoCertTrust
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$Root = Split-Path -Parent $PSScriptRoot
$Deploy = Join-Path $Root 'deploy\production'
$EnvFile = Join-Path $Deploy '.env.zarrar'
$AccountsFile = Join-Path $Root 'DEMO_ACCOUNTS.txt'
$Project = 'zarrar'

function Step($text) { Write-Host ''; Write-Host ">> $text" -ForegroundColor Red }
function Info($text) { Write-Host "   $text" -ForegroundColor Gray }
function Ok($text) { Write-Host "   $text" -ForegroundColor Green }
function Fail($text) {
    Write-Host ''
    Write-Host "   ERROR: $text" -ForegroundColor Yellow
    Write-Host ''
    Read-Host 'Press Enter to close'
    exit 1
}

function Secret {
    $bytes = New-Object byte[] 48
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    # base64url without padding: safe in .env files and shell scripts
    [Convert]::ToBase64String($bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function Read-EnvFile {
    $map = @{}
    foreach ($line in Get-Content $EnvFile) {
        if ($line -match '^\s*([A-Za-z0-9_]+)=(.*)$') { $map[$Matches[1]] = $Matches[2] }
    }
    $map
}

function Compose {
    # Run docker directly on this console: its progress goes to stderr, which PowerShell 5.1
    # would otherwise turn into error records. Returns only the exit code.
    $argList = @('compose', '-p', $Project, '--env-file', "`"$EnvFile`"",
        '-f', "`"$(Join-Path $Deploy 'compose.yaml')`"", '-f', "`"$(Join-Path $Deploy 'compose.local.yaml')`"") + $args
    $proc = Start-Process docker -ArgumentList $argList -NoNewWindow -Wait -PassThru
    return $proc.ExitCode
}

function Test-DockerEngine {
    $old = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    & docker info --format '{{.ServerVersion}}' *> $null
    $ok = $LASTEXITCODE -eq 0
    $ErrorActionPreference = $old
    return $ok
}

Write-Host ''
Write-Host '  ZARRAR - 1v1 Cyber Showdown' -ForegroundColor Red
Write-Host '  one-click local launcher' -ForegroundColor DarkGray

# ---------------------------------------------------------------- Docker Desktop
Step 'Checking Docker Desktop'
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Fail 'Docker is not installed. Install Docker Desktop from https://www.docker.com/products/docker-desktop/ and run Zarrar.exe again.'
}

if (-not (Test-DockerEngine)) {
    $desktop = @(
        "$env:ProgramFiles\Docker\Docker\Docker Desktop.exe",
        "$env:LOCALAPPDATA\Programs\Docker\Docker\Docker Desktop.exe"
    ) | Where-Object { Test-Path $_ } | Select-Object -First 1
    if (-not $desktop) { Fail 'Docker Desktop.exe was not found. Start Docker Desktop yourself and run Zarrar.exe again.' }

    Info 'Starting Docker Desktop (this can take a minute)...'
    Start-Process $desktop | Out-Null
    $deadline = (Get-Date).AddMinutes(4)
    while (-not (Test-DockerEngine)) {
        if ((Get-Date) -gt $deadline) { Fail 'Docker Desktop did not start within 4 minutes. Open it, wait for "Engine running", then run Zarrar.exe again.' }
        Start-Sleep -Seconds 3
        Write-Host '.' -NoNewline -ForegroundColor DarkGray
    }
    Write-Host ''
}
Ok 'Docker engine is running.'

# ---------------------------------------------------------------- Stop
if ($Stop) {
    if (-not (Test-Path $EnvFile)) { Ok 'Nothing to stop.'; exit 0 }
    Step 'Stopping ZARRAR'
    Compose stop | Out-Null
    Ok 'Stopped. Your data is kept; run Zarrar.exe to start again.'
    Start-Sleep -Seconds 3
    exit 0
}

# ---------------------------------------------------------------- Config (first run)
if (-not (Test-Path $EnvFile)) {
    Step 'First run: creating local configuration with fresh secrets'
    $lines = @(
        '# Generated by launcher\ZARRAR-Launcher.ps1 on first run. Keep it: the database is encrypted with these keys.',
        '# Delete this file AND the zarrar_* Docker volumes together to start completely fresh.',
        "COMPOSE_PROJECT_NAME=$Project",
        'ZARRAR_IMAGE=zarrar:local',
        'ZARRAR_MINIO_IMAGE=zarrar-minio:7aac2a2',
        'ZARRAR_MC_IMAGE=zarrar-minio-client:77f82e1',
        "ZARRAR_VOLUME_PREFIX=$Project",
        '',
        '# Address. localhost = this computer only. For other laptops on the LAN, see ZARRAR_SETUP.md section 4.',
        'ZARRAR_DOMAIN=localhost',
        'ZARRAR_PUBLIC_URL=https://localhost',
        'ZARRAR_ALLOWED_HOSTS=localhost',
        'ACME_EMAIL=internal',
        'ZARRAR_HTTP_PORT=80',
        'ZARRAR_HTTPS_PORT=443',
        'ZARRAR_PROXY_IP=172.30.0.10',
        'ZARRAR_APP_EDGE_IP=172.30.0.20',
        'ZARRAR_EDGE_SUBNET=172.30.0.0/24',
        '',
        "ZARRAR_XOR_KEY=$(Secret)",
        "ZARRAR_DYNAMIC_FLAG_HMAC_KEY=$(Secret)",
        "ZARRAR_SHARED_GATEWAY_SIGNING_KEY=$(Secret)",
        "ZARRAR_VARIANT_SEED_KEY=$(Secret)",
        'ZARRAR_BOOTSTRAP_ADMIN_PASSWORD=Zarrar-Admin-2026!',
        '',
        'ZARRAR_RUNTIME_PROVIDER=Docker',
        'DOCKER_GID=0',
        'ZARRAR_RUNTIME_SOCKET_SOURCE=/var/run/docker.sock',
        '',
        'POSTGRES_DB=zarrar',
        'POSTGRES_USER=zarrar',
        "POSTGRES_PASSWORD=$(Secret)",
        "REDIS_PASSWORD=$(Secret)",
        'MINIO_ROOT_USER=zarrar-storage',
        "MINIO_ROOT_PASSWORD=$(Secret)",
        'MINIO_ACCESS_KEY=zarrar-app',
        "MINIO_SECRET_KEY=$(Secret)",
        'MINIO_BUCKET=zarrar',
        '',
        '# Demo accounts created on first start (change before the first run if you like)',
        'DEMO_PASSWORD_MONITOR=Zarrar-Monitor-2026!',
        'DEMO_PASSWORD_PLAYER=Zarrar-Player-2026!',
        'DEMO_SEEDED=false'
    )
    Set-Content -Path $EnvFile -Value $lines -Encoding ASCII
    Ok "Wrote $EnvFile"
}
$cfg = Read-EnvFile

# ---------------------------------------------------------------- Ports
foreach ($port in @([int]$cfg['ZARRAR_HTTP_PORT'], [int]$cfg['ZARRAR_HTTPS_PORT'])) {
    $busy = Get-NetTCPConnection -State Listen -LocalPort $port -ErrorAction SilentlyContinue |
        Where-Object { (Get-Process -Id $_.OwningProcess -ErrorAction SilentlyContinue).ProcessName -notmatch 'com.docker|wslrelay|vpnkit|docker' }
    if ($busy) {
        $name = (Get-Process -Id $busy[0].OwningProcess -ErrorAction SilentlyContinue).ProcessName
        Fail "Port $port is already used by '$name'. Close it (IIS, Skype, another web server) and run Zarrar.exe again."
    }
}

# ---------------------------------------------------------------- Build + start
function Test-Image($name) {
    $old = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    & docker image inspect $name *> $null
    $found = $LASTEXITCODE -eq 0
    $ErrorActionPreference = $old
    return $found
}

# Build only the images that are missing (the app image again with -Rebuild). The MinIO images
# are compiled from GitHub sources, so a flaky download is retried.
$toBuild = @()
if ($Rebuild -or -not (Test-Image $cfg['ZARRAR_IMAGE'])) { $toBuild += 'zarrar' }
if (-not (Test-Image $cfg['ZARRAR_MINIO_IMAGE'])) { $toBuild += 'minio' }
if (-not (Test-Image $cfg['ZARRAR_MC_IMAGE'])) { $toBuild += 'minio-init' }

# The edge network needs fixed addresses (the app trusts the proxy by IP). If another Docker
# project already uses the configured /24, move ZARRAR to a free 10.250.x.0/24.
$old = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
& docker network inspect "${Project}_edge" *> $null
$haveEdge = $LASTEXITCODE -eq 0
$used = @(& docker network ls -q | ForEach-Object { & docker network inspect $_ --format '{{range .IPAM.Config}}{{.Subnet}} {{end}}' }) -join ' '
$ErrorActionPreference = $old
if (-not $haveEdge) {
    $taken = $used -split '\s+' | Where-Object { $_ } | ForEach-Object { ($_ -split '/')[0] -replace '\.\d+$', '' }
    $prefix = ($cfg['ZARRAR_EDGE_SUBNET'] -split '/')[0] -replace '\.\d+$', ''
    $broad = $used -split '\s+' | Where-Object { $_ -match '/(8|12|16)$' } | ForEach-Object { (($_ -split '/')[0] -split '\.')[0..1] -join '.' }
    $clash = { param($p) ($taken -contains $p) -or ($broad -contains ((($p -split '\.')[0..1]) -join '.')) }
    if (& $clash $prefix) {
        $free = 1..254 | ForEach-Object { "10.250.$_" } | Where-Object { -not (& $clash $_) } | Select-Object -First 1
        Info "Subnet $($cfg['ZARRAR_EDGE_SUBNET']) is used by another Docker network; switching to $free.0/24."
        (Get-Content $EnvFile) `
            -replace '^ZARRAR_EDGE_SUBNET=.*$', "ZARRAR_EDGE_SUBNET=$free.0/24" `
            -replace '^ZARRAR_PROXY_IP=.*$', "ZARRAR_PROXY_IP=$free.10" `
            -replace '^ZARRAR_APP_EDGE_IP=.*$', "ZARRAR_APP_EDGE_IP=$free.20" | Set-Content $EnvFile -Encoding ASCII
        $cfg = Read-EnvFile
    }
}

foreach ($service in $toBuild) {
    Step "Building the '$service' image (first time takes 5-15 minutes; later starts skip this)"
    $built = $false
    for ($try = 1; $try -le 3 -and -not $built; $try++) {
        if ($try -gt 1) { Info "Retrying ($try of 3)..."; Start-Sleep -Seconds 5 }
        $built = (Compose build $service) -eq 0
    }
    if (-not $built) { Fail "Building '$service' failed 3 times. Check the internet connection and the messages above." }
}

Step 'Starting ZARRAR (Caddy, app, PostgreSQL, Redis, MinIO)'
if ((Compose up -d --remove-orphans --no-build) -ne 0) { Fail 'docker compose up failed. Scroll up for the reason.' }

Step 'Waiting for the platform to become healthy'
$deadline = (Get-Date).AddMinutes(5)
while ($true) {
    $old = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    $state = & docker inspect --format '{{.State.Health.Status}}' "$Project-zarrar-1" 2>$null
    $ErrorActionPreference = $old
    if ($state -eq 'healthy') { break }
    if ((Get-Date) -gt $deadline) {
        Compose logs --tail 60 zarrar | Out-Null
        Fail 'The app did not become healthy within 5 minutes. The last log lines are above.'
    }
    Start-Sleep -Seconds 3
    Write-Host '.' -NoNewline -ForegroundColor DarkGray
}
Write-Host ''
Ok 'Platform is up.'

# ---------------------------------------------------------------- HTTPS certificate
Step 'Checking the local HTTPS certificate'
$certPath = Join-Path $env:TEMP 'zarrar-root.crt'
$certReady = $false
for ($i = 0; $i -lt 20 -and -not $certReady; $i++) {
    $old = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    & docker cp "$Project-proxy-1:/data/caddy/pki/authorities/local/root.crt" $certPath *> $null
    $certReady = $LASTEXITCODE -eq 0
    $ErrorActionPreference = $old
    if (-not $certReady) { Start-Sleep -Seconds 2 }
}
if ($certReady) {
    $cert = New-Object System.Security.Cryptography.X509Certificates.X509Certificate2 $certPath
    $trusted = Get-ChildItem Cert:\CurrentUser\Root | Where-Object Thumbprint -eq $cert.Thumbprint
    if ($trusted) {
        Ok 'Certificate already trusted.'
    } elseif ($NoCertTrust) {
        Info 'Skipped trusting the certificate (-NoCertTrust).'
    } else {
        Info 'Windows will ask once whether to trust the "Caddy Local Authority" certificate. Click Yes.'
        try {
            Import-Certificate -FilePath $certPath -CertStoreLocation Cert:\CurrentUser\Root | Out-Null
            Ok 'Certificate trusted. Restart Chrome/Edge if a page still shows a warning.'
        } catch {
            Info 'Certificate not trusted. The browser will show a warning; click Advanced -> Proceed.'
        }
    }
    Copy-Item $certPath (Join-Path $Root 'zarrar-root.crt') -Force
} else {
    Info 'Could not read the certificate yet; the browser may show a warning (Advanced -> Proceed).'
}

# ---------------------------------------------------------------- Demo accounts (once)
if ($cfg['DEMO_SEEDED'] -ne 'true') {
    Step 'Creating demo accounts'
    # Talk to Caddy over https://localhost; accept its local certificate for these calls only.
    Add-Type -TypeDefinition @'
using System.Net;
using System.Net.Security;
using System.Security.Cryptography.X509Certificates;
public static class ZarrarTls {
    public static void AcceptLocal() {
        ServicePointManager.SecurityProtocol = SecurityProtocolType.Tls12;
        ServicePointManager.ServerCertificateValidationCallback =
            (s, c, ch, e) => e == SslPolicyErrors.None || ((HttpWebRequest)s).RequestUri.Host == "localhost";
    }
}
'@
    [ZarrarTls]::AcceptLocal()

    $base = "https://localhost:$($cfg['ZARRAR_HTTPS_PORT'])"
    $headers = @{ Origin = $cfg['ZARRAR_PUBLIC_URL'] }
    $session = $null
    $loginBody = @{ userName = 'Admin'; password = $cfg['ZARRAR_BOOTSTRAP_ADMIN_PASSWORD'] } | ConvertTo-Json
    try {
        Invoke-RestMethod -Uri "$base/api/account/login" -Method Post -Body $loginBody -ContentType 'application/json' -Headers $headers -SessionVariable session | Out-Null
    } catch { Fail "Admin login failed: $($_.Exception.Message)" }

    $mp = $cfg['DEMO_PASSWORD_MONITOR']; $pp = $cfg['DEMO_PASSWORD_PLAYER']
    $users = @(
        @{ userName = 'monitor'; password = $mp; email = 'monitor@zarrar.local'; realName = 'Projector Stage' },
        @{ userName = 'player1'; password = $pp; email = 'player1@zarrar.local'; realName = 'Player One'; teamName = 'Team-Alpha' },
        @{ userName = 'player2'; password = $pp; email = 'player2@zarrar.local'; realName = 'Player Two'; teamName = 'Team-Bravo' },
        @{ userName = 'player3'; password = $pp; email = 'player3@zarrar.local'; realName = 'Player Three'; teamName = 'Team-Alpha' }
    )
    try {
        Invoke-RestMethod -Uri "$base/api/admin/users" -Method Post -Body (ConvertTo-Json @($users)) -ContentType 'application/json' -Headers $headers -WebSession $session | Out-Null
        $found = Invoke-RestMethod -Uri "$base/api/admin/users/search?hint=monitor" -Method Post -Headers $headers -WebSession $session
        $monitor = @($found.data) | Where-Object { $_.userName -eq 'monitor' } | Select-Object -First 1
        $roleBody = @{ role = 2; emailConfirmed = $true } | ConvertTo-Json
        Invoke-RestMethod -Uri "$base/api/admin/users/$($monitor.id)" -Method Put -Body $roleBody -ContentType 'application/json' -Headers $headers -WebSession $session | Out-Null
    } catch { Fail "Creating demo accounts failed: $($_.Exception.Message)" }

    (Get-Content $EnvFile) -replace '^DEMO_SEEDED=.*$', 'DEMO_SEEDED=true' | Set-Content $EnvFile -Encoding ASCII

    $text = @(
        'ZARRAR demo accounts (created by Zarrar.exe)',
        '=============================================',
        "Website : $($cfg['ZARRAR_PUBLIC_URL'])",
        '',
        "Admin   : Admin    / $($cfg['ZARRAR_BOOTSTRAP_ADMIN_PASSWORD'])   -> $($cfg['ZARRAR_PUBLIC_URL'])/admin",
        "Monitor : monitor  / $mp   -> $($cfg['ZARRAR_PUBLIC_URL'])/monitor/login",
        "Player 1: player1  / $pp   (team Team-Alpha)",
        "Player 2: player2  / $pp   (team Team-Bravo)",
        "Player 3: player3  / $pp   (team Team-Alpha, for tag-team swaps)",
        '',
        'These are demo passwords for this computer only. Change them before a real event.',
        'Stop the platform: Zarrar-Stop.exe   Rebuild after code changes: Zarrar.exe -Rebuild'
    )
    Set-Content -Path $AccountsFile -Value $text -Encoding UTF8
    Ok 'Demo accounts created.'
}

# ---------------------------------------------------------------- Done
Write-Host ''
Get-Content $AccountsFile -ErrorAction SilentlyContinue | ForEach-Object { Write-Host "   $_" -ForegroundColor White }
Write-Host ''
Ok "ZARRAR is running at $($cfg['ZARRAR_PUBLIC_URL'])"
if (-not $NoBrowser) { Start-Process $cfg['ZARRAR_PUBLIC_URL'] }
Write-Host '   This window closes in 15 seconds. The platform keeps running in Docker.' -ForegroundColor DarkGray
Start-Sleep -Seconds 15
